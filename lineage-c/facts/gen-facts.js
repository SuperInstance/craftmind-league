// gen-facts.js — generate facts/recipes.md from the game's own data tables
// (minecraft-data for the pinned version). GITM's facts came from the wiki;
// ours are generated from minecraft-data, the same tables the bot runtime uses.
// Run on the Thor from this directory:  node facts/gen-facts.js
//
// Variant handling: minecraft-data lists one recipe variant per material
// choice (oak planks, cherry planks, ...). Facts must name the GROUP, not one
// arbitrary variant — so ingredient names are folded through GROUPS below
// (any *_planks -> "planks (any wood)", the stone-tool materials -> one tier,
// coal/charcoal -> one entry). The first variant's grouped counts are
// canonical; all variants of these simple recipes agree after grouping.
const fs = require("fs");
const path = require("path");
const mcData = require("minecraft-data")(process.env.MC_VERSION || "26.1");

const WANT = [
  // wood chain
  "oak_log","spruce_log","birch_log","jungle_log","acacia_log","dark_oak_log",
  "oak_planks","spruce_planks","birch_planks","jungle_planks","acacia_planks","dark_oak_planks",
  "stick","crafting_table",
  // wooden + stone tools
  "wooden_pickaxe","wooden_axe","wooden_shovel","wooden_sword","wooden_hoe",
  "stone_pickaxe","stone_axe","stone_shovel","stone_sword","stone_hoe",
  // shelter + furnish
  "oak_door","spruce_door","birch_door","jungle_door","acacia_door","dark_oak_door",
  "torch","chest","furnace","oak_trapdoor",
  // food / misc
  "apple","bread","cooked_beef","cooked_porkchop","cooked_mutton","cooked_chicken",
  "white_bed","oak_boat","flint_and_steel","bucket","iron_pickaxe",
];

function groupOf(name) {
  if (/_planks$/.test(name)) return "planks(any wood)";
  if (/_log$/.test(name)) return "log(any wood)";
  if (name === "cobblestone" || name === "cobbled_deepslate" || name === "blackstone") return "cobblestone-tier(cobblestone/cobbled deepslate/blackstone)";
  if (name === "coal" || name === "charcoal") return "coal-or-charcoal";
  return name;
}
const nameOf = (id) => (mcData.items[id] || mcData.blocks[id] || {}).name || ("#" + id);

function countsOf(cells) {
  const counts = {};
  for (const cell of cells) {
    if (cell == null || cell < 0) continue;
    const g = groupOf(nameOf(cell));
    counts[g] = (counts[g] || 0) + 1;
  }
  return Object.entries(counts).map(([n, c]) => `${c}x ${n}`).join(" + ");
}

function recipeText(item) {
  const id = mcData.itemsByName[item] && mcData.itemsByName[item].id;
  const recs = (mcData.recipes && id != null && mcData.recipes[id]) || [];
  if (!recs.length) return `- ${item}: (no crafting recipe — gathered or smelted)`;
  const seen = new Set();
  const lines = [];
  for (const r of recs) {
    let line = null;
    if (r.inShape) {
      const flat = [];
      for (const row of r.inShape) for (const cell of row) flat.push(cell);
      const needsTable = r.inShape.length >= 3 || (r.inShape[0] && r.inShape[0].length >= 3);
      line = `${needsTable ? "3x3 grid (crafting table)" : "2x2 grid (no table)"}: ${countsOf(flat)}`;
    } else if (r.ingredients) {
      line = `shapeless (2x2 grid): ${countsOf(r.ingredients)}`;
    }
    if (!line || seen.has(line)) continue;
    seen.add(line);
    const resCount = (r.result && r.result.count) || 1;
    lines.push(`${line} -> ${resCount}x ${item}`);
    if (lines.length >= 2) break;
  }
  return `- ${item}:\n` + lines.map((l) => `    ${l}`).join("\n");
}

const out = [];
out.push("# recipes.md — generated from minecraft-data " + (process.env.MC_VERSION || "26.1"));
out.push("# Generated by facts/gen-facts.js from the game's own recipe tables.");
out.push("# Ingredient names are material GROUPS where the game accepts variants");
out.push("# (e.g. planks(any wood) = oak, spruce, birch... planks all work).");
out.push("");
out.push("## Gathered, not crafted");
out.push("- any *_log: dug from tree trunks by hand.");
out.push("- cobblestone: stone dug with any pickaxe drops cobblestone 1:1.");
out.push("- coal: coal_ore dug with any pickaxe drops coal 1:1.");
out.push("- dirt, gravel, sand: dug by hand or shovel.");
out.push("");
out.push("## Recipes");
for (const item of WANT) out.push(recipeText(item));
out.push("");
out.push("## Smelting (furnace, any fuel: planks, logs, coal, charcoal)");
out.push("- 1x log -> 1x charcoal");
out.push("- 1x raw_beef -> 1x cooked_beef; raw_porkchop -> cooked_porkchop;");
out.push("  raw_mutton -> cooked_mutton; raw_chicken -> cooked_chicken; potato -> baked_potato");
out.push("");

const dest = path.join(__dirname, "recipes.md");
fs.writeFileSync(dest, out.join("\n"));
console.log("wrote", dest, out.join("\n").length, "bytes for version", mcData.version && mcData.version.minecraftVersion);
